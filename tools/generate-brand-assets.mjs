import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const res = path.join(root, 'android/app/src/main/res');
const brand = path.join(root, 'assets/brand');
const palettes = {
  light: { ground: '#F5F5F7', surface: '#F5F5F7', blue: '#0071E3', flame: '#FF6B00', ink: '#1D1D1F' },
  dark: { ground: '#000000', surface: '#1C1C1E', blue: '#2997FF', flame: '#FF6B00', ink: '#F5F5F7' },
};

// One 108-unit drawing feeds SVG, Android vectors, and all raster densities.
// The book and rising waveform both stay inside Android's 66-dp safe circle.
const shapes = [
  ['blue', 'M29,43 C37,39 45,39 51,44 L51,75 C44,70 36,70 29,73 C27,74 26,73 26,71 L26,47 C26,45 27,44 29,43 Z'],
  ['blue', 'M79,43 C71,39 63,39 57,44 L57,75 C64,70 72,70 79,73 C81,74 82,73 82,71 L82,47 C82,45 81,44 79,43 Z'],
  ['flame', 'M45,29 C45,27.9 45.9,27 47,27 C48.1,27 49,27.9 49,29 L49,35 C49,36.1 48.1,37 47,37 C45.9,37 45,36.1 45,35 Z'],
  ['flame', 'M52,24 C52,22.9 52.9,22 54,22 C55.1,22 56,22.9 56,24 L56,35 C56,36.1 55.1,37 54,37 C52.9,37 52,36.1 52,35 Z'],
  ['flame', 'M59,29 C59,27.9 59.9,27 61,27 C62.1,27 63,27.9 63,29 L63,35 C63,36.1 62.1,37 61,37 C59.9,37 59,36.1 59,35 Z'],
  ['paper', 'M34,51 C37,50.5 41,51 44,52 L44,55 C41,54 37,53.5 34,54 Z'],
  ['paper', 'M34,59 C37,58.5 41,59 44,60 L44,63 C41,62 37,61.5 34,62 Z'],
  ['paper', 'M64,52 C67,51 71,50.5 74,51 L74,54 C71,53.5 67,54 64,55 Z'],
  ['paper', 'M64,60 C67,59 71,58.5 74,59 L74,62 C71,61.5 67,62 64,63 Z'],
];

function write(file, data) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
}

function mark(palette, monochrome = false) {
  return `<g transform="translate(54 54) scale(.97) translate(-54 -54)">${shapes.map(([color, d]) => `<path fill="${monochrome ? '#FFFFFF' : color === 'paper' ? palette.surface : palette[color]}" d="${d}"/>`).join('')}</g>`;
}

function svg(body, width = 108, height = width) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">${body}</svg>\n`;
}

function icon(palette, mask = '') {
  const shape = mask === 'round' ? '<circle cx="54" cy="54" r="54"/>' : '<rect width="108" height="108" rx="23"/>';
  return svg(`<defs><clipPath id="mask">${shape}</clipPath></defs><g clip-path="url(#mask)"><rect width="108" height="108" fill="${palette.surface}"/><g transform="translate(-27 -27) scale(1.5)">${mark(palette)}</g></g>`);
}

function png(source, size) {
  return new Resvg(source, {
    fitTo: { mode: 'width', value: size },
    font: { loadSystemFonts: false, fontFiles: source.includes('<text') ? [path.join(res, 'font/noto_sans_sc.ttf')] : [] },
  }).render().asPng();
}

function vector(size, monochrome = false) {
  const paths = shapes.map(([color, d]) => `    <path android:fillColor="${monochrome ? '#FFFFFF' : color === 'paper' ? '@color/ic_launcher_background' : `@color/brand_${color}`}" android:pathData="${d}"/>`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by npm run assets:generate.${size === 288 ? ' Android splash icons without a background require a 288-dp canvas.' : ''} -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"${size === 288 ? ' xmlns:tools="http://schemas.android.com/tools" tools:ignore="VectorRaster"' : ''} android:width="${size}dp" android:height="${size}dp" android:viewportWidth="108" android:viewportHeight="108">\n    <group android:pivotX="54" android:pivotY="54" android:scaleX="0.97" android:scaleY="0.97">\n${paths}\n    </group>\n</vector>\n`;
}

for (const [mode, palette] of Object.entries(palettes)) {
  write(path.join(brand, `icon-${mode}.svg`), icon(palette));
  write(path.join(brand, `icon-${mode}.png`), png(icon(palette), 1024));
  write(path.join(brand, `foreground-${mode}.svg`), svg(mark(palette)));
  for (const [density, factor] of [['mdpi', 1], ['hdpi', 1.5], ['xhdpi', 2], ['xxhdpi', 3], ['xxxhdpi', 4]]) {
    const dir = path.join(res, `mipmap-${mode === 'dark' ? 'night-' : ''}${density}`);
    write(path.join(dir, 'ic_launcher.png'), png(icon(palette), 48 * factor));
    write(path.join(dir, 'ic_launcher_round.png'), png(icon(palette, 'round'), 48 * factor));
    write(path.join(dir, 'ic_launcher_foreground.png'), png(svg(mark(palette)), 108 * factor));
  }
  const colors = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from the cherina-pod tokens by npm run assets:generate. -->\n<resources>\n    <color name="brand_blue">${palette.blue}</color>\n    <color name="brand_flame">${palette.flame}</color>\n    <color name="ic_launcher_background">${palette.surface}</color>\n    <color name="splash_background">${palette.ground}</color>\n</resources>\n`;
  write(path.join(res, mode === 'dark' ? 'values-night' : 'values', 'brand_colors.xml'), colors);
  const splash = svg(`<rect width="360" height="780" fill="${palette.ground}"/><svg x="36" y="246" width="288" height="288" viewBox="0 0 108 108">${mark(palette)}</svg>`, 360, 780);
  write(path.join(brand, `splash-${mode}.svg`), splash);
}

write(path.join(res, 'drawable', 'ic_launcher_foreground.xml'), vector(108));
write(path.join(res, 'drawable', 'ic_launcher_monochrome.xml'), vector(108, true));
write(path.join(res, 'drawable', 'splash_mark.xml'), vector(288));

for (const name of ['ic_launcher', 'ic_launcher_round']) {
  for (const api of [26, 33]) {
    write(path.join(res, `mipmap-anydpi-v${api}`, `${name}.xml`), `<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background"/>\n    <foreground android:drawable="@${api === 26 ? 'mipmap' : 'drawable'}/ic_launcher_foreground"/>\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n`);
  }
}

// Explicit template files only; no recursive cleanup of the Android resource tree.
for (const name of ['drawable/splash.png', 'drawable/splash.xml', 'drawable/ic_launcher_background.xml', 'drawable-v24/ic_launcher_foreground.xml', 'values/ic_launcher_background.xml',
  ...['port', 'land'].flatMap(orientation => ['mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi'].map(density => `drawable-${orientation}-${density}/splash.png`))]) {
  fs.rmSync(path.join(res, name), { force: true });
}

write(path.join(root, 'web/read/favicon.svg'), icon(palettes.light));
write(path.join(root, 'web/favicon.svg'), icon(palettes.light));

