@Composable
private fun RowScope.GlassTab(index: Int) {
    val dark = isSystemInDarkTheme()
    val color = if (dark) Ink2Dark else Ink2Light
    LiquidBottomTab(onClick = { GlassState.onTab(index) }) {
        Image(if (LocalTintedTabRow.current) selectedIcons[index] else icons[index], null, Modifier.size(24.dp), colorFilter = androidx.compose.ui.graphics.ColorFilter.tint(color))
        BasicText(labels[index], style = TextStyle(color = color, fontSize = 11.sp,
            fontWeight = androidx.compose.ui.text.font.FontWeight.SemiBold,
            fontFamily = tabLabelFont))
    }
}

/** The bar, aligned bottom, 8dp above the nav inset; slides fully away when hidden. */
@Composable
fun GlassTabBar(backdrop: Backdrop, collapse: Float) {
    val density = androidx.compose.ui.platform.LocalDensity.current
    val navBottomDp = WindowInsets.navigationBars.getBottom(density) / density.density
    // Bar 64dp + 8dp bottom offset + real nav inset — fully off-screen.
    val hideDp = 64f + 8f + navBottomDp
    Box(
        Modifier
            .fillMaxWidth()
            .navigationBarsPadding()
            .padding(horizontal = 12.dp)
            .padding(bottom = 8.dp)
            .graphicsLayer {
                translationY = hideDp * density.density * collapse
                alpha = 1f - collapse
            }
    ) {
        LiquidBottomTabs(
            selectedTabIndex = { GlassState.selected.intValue },
            onTabSelected = { GlassState.onTab(it) },
            backdrop = backdrop,
            tabsCount = 3
        ) {
            for (i in 0..2) GlassTab(i)
        }
    }
}
